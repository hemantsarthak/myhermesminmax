#!/usr/bin/env python3
"""Parse usercreds.txt into a gitignored .env for this project.

Never prints secret values. Prints only a classification map: label, kind,
length. Idempotent — safe to re-run.

Usage:
    python scripts/parse_creds.py [--src ../../usercreds.txt] [--out .env]
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

# label -> env var name. Matching is case-insensitive on the label text.
LABEL_MAP = [
    (r"git\s*fine\s*grained\s*token", "GITHUB_PAT"),
    (r"your\s*api\s*token", "CLOUDFLARE_API_TOKEN"),
    (r"^account\s*id$", "CLOUDFLARE_ACCOUNT_ID"),
    (r"access\s*key\s*id", "R2_ACCESS_KEY_ID"),
    (r"secret\s*access\s*key", "R2_SECRET_ACCESS_KEY"),
    (r"s3\s*api\s*endpoint", "R2_S3_ENDPOINT"),
]

TOKENISH = re.compile(r"^(gh[pousr]_|github_pat_|cfat_|sk-|AKIA)[A-Za-z0-9_\-]+$")
HEXISH = re.compile(r"^[0-9a-f]{32,}$")
URLISH = re.compile(r"^https?://\S+$")
ACCOUNTISH = re.compile(r"^[0-9a-f]{32}$")


def classify(value: str) -> str:
    v = value.strip()
    if not v:
        return "blank"
    if URLISH.match(v):
        return "url"
    if TOKENISH.match(v):
        return "token"
    if ACCOUNTISH.match(v):
        return "hex-id"
    if HEXISH.match(v):
        return "hex"
    return "opaque"


def main() -> int:
    ap = argparse.ArgumentParser()
    here = pathlib.Path(__file__).resolve().parent.parent
    ap.add_argument("--src", default=str(here.parent / "usercreds.txt"))
    ap.add_argument("--out", default=str(here / ".env"))
    args = ap.parse_args()

    src = pathlib.Path(args.src)
    if not src.exists():
        print(f"ERROR: {src} not found", file=sys.stderr)
        return 2

    lines = src.read_text(encoding="utf-8", errors="replace").splitlines()
    found: dict[str, str] = {}
    pending_label: str | None = None

    for i, raw in enumerate(lines):
        line = raw.strip()
        if not line:
            continue
        low = line.lower()

        # A line that matches a known label phrase sets the pending slot.
        matched = None
        for pattern, env_name in LABEL_MAP:
            if re.search(pattern, low):
                matched = env_name
                break
        if matched:
            pending_label = matched
            continue

        kind = classify(line)
        if kind not in {"token", "hex", "hex-id", "url"}:
            continue

        # Value line. Use the pending label if we have one, else infer from
        # the value's own shape (global fallback for unlabeled tokens).
        if pending_label:
            found[pending_label] = line
            pending_label = None
            continue

        if line.startswith("github_pat_"):
            found.setdefault("GITHUB_PAT", line)
        elif line.startswith("cfat_"):
            found.setdefault("CLOUDFLARE_API_TOKEN", line)
        elif ".r2.cloudflarestorage.com" in line:
            found.setdefault("R2_S3_ENDPOINT", line)

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    lines_out = [
        "# Generated by scripts/parse_creds.py — gitignored, never commit.",
        "# Regenerate with: python scripts/parse_creds.py",
        "",
    ]
    for name in ("GITHUB_PAT", "CLOUDFLARE_API_TOKEN", "CLOUDFLARE_ACCOUNT_ID",
                 "R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY", "R2_S3_ENDPOINT"):
        if name in found:
            lines_out.append(f'{name}="{found[name]}"')

    # Non-secret project config
    lines_out += [
        "",
        "GITHUB_REPO=hemantsarthak/myhermesminmax",
        "GITHUB_BRANCH=main",
        "CLOUDFLARE_PAGES_PROJECT=moneymmax",
        "PRIMARY_DOMAIN=tekify.xyz",
        "",
    ]
    out.write_text("\n".join(lines_out), encoding="utf-8")

    # Classification map only — no values.
    print(f"source: {src}")
    print(f"output: {out}  (mode: 0600 recommended)")
    for name in ("GITHUB_PAT", "CLOUDFLARE_API_TOKEN", "CLOUDFLARE_ACCOUNT_ID",
                 "R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY", "R2_S3_ENDPOINT"):
        if name in found:
            v = found[name]
            print(f"  {name:26s} {classify(v):10s} len={len(v)}")
        else:
            print(f"  {name:26s} {'MISSING':10s}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
